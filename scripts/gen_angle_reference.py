#!/usr/bin/env python3
"""Write the topic-research skill's angle reference from the angle data.

The kinds an angle can be and the signals of its score live in
tubematic_core/angles.py, which the server validates against. The skill needs
them as text an agent reads. This script renders that text into the block
between the two markers in the skill, so there is one place to edit a kind or
a signal.

    python3 scripts/gen_angle_reference.py           # rewrite the block
    python3 scripts/gen_angle_reference.py --check    # exit 1 if it is out of date

Run it after changing ANGLE_KINDS or ANGLE_RUBRIC. A test runs the same
comparison, so an edit made without it fails the suite.
"""
import argparse
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from tubematic_core import angles as tangles  # noqa: E402

SKILL = REPO / "agent_files" / "skills" / "tubematic-topic-research" / "SKILL.md"
START = "<!-- angle-reference:start (generated by scripts/gen_angle_reference.py) -->\n"
END = "<!-- angle-reference:end -->\n"


def with_reference(skill_text: str) -> str:
    """SKILL.md with the block between the two markers replaced by the reference."""
    head, sep, rest = skill_text.partition(START)
    _old, sep2, tail = rest.partition(END)
    if not sep or not sep2:
        raise SystemExit(f"{SKILL} has no angle-reference markers")
    return head + START + tangles.reference_markdown() + END + tail


def stale() -> bool:
    """Whether the skill's block differs from what the data renders."""
    text = SKILL.read_text(encoding="utf-8")
    return with_reference(text) != text


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="report a stale block and change nothing")
    args = ap.parse_args(argv)
    if args.check:
        if stale():
            print(f"out of date: {SKILL.relative_to(REPO)}")
            return 1
        return 0
    SKILL.write_text(with_reference(SKILL.read_text(encoding="utf-8")), encoding="utf-8")
    print(f"wrote the angle reference in {SKILL.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
