"""NVIDIA GPU passthrough for the render worker.

The GPU is handed to `tubematic-renderer` by a Compose override file that the
`gpu` onboarding step writes and `_compose()` loads when it exists. Everything
here is host-side; the worker decides per render whether the GPU actually
works (renderer/api/worker.py::_gl_args), so a stale or bypassed override
falls back to CPU rendering rather than failing a video.

Why an override file, and why under the data root:
- Passthrough is a property of how the container is created, so it has to be
  in the Compose configuration. It cannot be a settings row the worker reads.
- `docker-compose.yml` is the same file on every install. A GPU reservation in
  it would stop every install without the NVIDIA runtime from starting
  ("could not select device driver").
- Upgrades install into a new directory, so a file beside the checkout would
  be left behind. ~/.tubematic-data is the machine-state root that already
  carries the database and secrets across upgrades.

It is JSON, which Compose reads as YAML, so writing and reading it back needs
no YAML library in the onboarding venv.
"""
import json
import subprocess
from dataclasses import asdict, dataclass
from pathlib import Path

from onboard.config import DATA_ROOT

OVERRIDE_PATH = DATA_ROOT / "compose.gpu.json"
RENDERER_SERVICE = "tubematic-renderer"

# graphics: the EGL/OpenGL driver libraries Chromium's WebGL needs. Toolkit 1.20
# injects them for any `--gpus` request, but older toolkits default to
# `compute,utility` and leave them out, so this is stated rather than assumed.
# utility: nvidia-smi inside the container, which the worker's probe reports.
DRIVER_CAPABILITIES = "graphics,utility"

STEP_HINT = "python3 onboard.py --step gpu"
DOCS_HINT = "docs/user-guide/10-gpu-rendering.md"


@dataclass(frozen=True)
class Gpu:
    index: int
    uuid: str
    name: str
    memory_mib: int | None
    driver: str

    def label(self) -> str:
        mem = f", {self.memory_mib // 1024} GB" if self.memory_mib else ""
        return f"GPU {self.index}: {self.name}{mem}"


def override_path() -> Path:
    """Looked up at call time so tests can point it elsewhere."""
    return OVERRIDE_PATH


def parse_nvidia_smi(text: str) -> list[Gpu]:
    """Rows of `--query-gpu=index,uuid,name,memory.total,driver_version
    --format=csv,noheader,nounits`. A row that does not parse is skipped, never
    guessed at: offering a GPU with a mangled UUID would write an override that
    fails at `up`."""
    gpus = []
    for line in text.splitlines():
        parts = [p.strip() for p in line.split(",")]
        if len(parts) < 5:
            continue
        index, uuid, driver, memory = parts[0], parts[1], parts[-1], parts[-2]
        name = ", ".join(parts[2:-2])  # a name containing a comma stays whole
        if not index.isdigit() or not uuid.startswith("GPU-") or not name:
            continue
        gpus.append(Gpu(int(index), uuid, name,
                        int(memory) if memory.isdigit() else None, driver))
    return gpus


def list_gpus(run=None) -> list[Gpu] | None:
    """The host's NVIDIA GPUs, or None when nvidia-smi is missing or fails —
    which is how a missing or unloaded driver presents (including a Secure
    Boot-rejected kernel module)."""
    run = run or subprocess.run
    try:
        r = run(["nvidia-smi",
                 "--query-gpu=index,uuid,name,memory.total,driver_version",
                 "--format=csv,noheader,nounits"],
                capture_output=True, text=True, timeout=20)
    except (OSError, subprocess.TimeoutExpired):
        return None
    if r.returncode != 0:
        return None
    return parse_nvidia_smi(r.stdout)


def docker_has_nvidia_runtime(run=None) -> bool | None:
    """Whether Docker knows the `nvidia` runtime that `nvidia-ctk runtime
    configure --runtime=docker` registers. None when Docker cannot be asked."""
    run = run or subprocess.run
    try:
        r = run(["docker", "info", "--format", "{{json .Runtimes}}"],
                capture_output=True, text=True, timeout=20)
    except (OSError, subprocess.TimeoutExpired):
        return None
    if r.returncode != 0:
        return None
    try:
        runtimes = json.loads(r.stdout or "{}")
    except ValueError:
        return None
    return isinstance(runtimes, dict) and "nvidia" in runtimes


def render_override(selected: Gpu, host_gpus: list[Gpu]) -> str:
    """The override file's text. Only tubematic-renderer changes."""
    doc = {
        "x-tubematic": ("Written by `python3 onboard.py --step gpu`. Re-run that step to "
                        "change or remove the GPU; do not edit this file by hand."),
        "services": {
            RENDERER_SERVICE: {
                "environment": [
                    f"NVIDIA_DRIVER_CAPABILITIES={DRIVER_CAPABILITIES}",
                    f"TUBEMATIC_GPU_UUID={selected.uuid}",
                    f"TUBEMATIC_GPU_NAME={selected.name}",
                    # Every GPU on the host when onboarding ran, so the
                    # dashboard can list them; the API container has no other
                    # way to see the host.
                    "TUBEMATIC_HOST_GPUS=" + json.dumps(
                        [asdict(g) for g in host_gpus], separators=(",", ":")),
                ],
                "deploy": {"resources": {"reservations": {"devices": [{
                    "driver": "nvidia",
                    "device_ids": [selected.uuid],
                    "capabilities": ["gpu"],
                }]}}},
            },
        },
    }
    return json.dumps(doc, indent=2) + "\n"


def read_override(path: Path = None) -> dict | None:
    """{"uuid", "name"} from an existing override, None when there is none.
    Raises ValueError for a file that exists but is not one this module wrote."""
    path = path or override_path()
    if not path.is_file():
        return None
    try:
        doc = json.loads(path.read_text())
        env = doc["services"][RENDERER_SERVICE]["environment"]
        values = dict(item.split("=", 1) for item in env if "=" in item)
        return {"uuid": values["TUBEMATIC_GPU_UUID"], "name": values.get("TUBEMATIC_GPU_NAME", "")}
    except (ValueError, KeyError, TypeError, AttributeError) as e:
        raise ValueError(f"{path} is not a GPU override this installer wrote ({e})") from e


def override_problems(path: Path = None, *, run=None) -> list[str]:
    """Why `docker compose up` would fail with the current override, if it
    would. Empty when there is no override or it is usable.

    Docker refuses to create a container whose device request it cannot
    satisfy, so a missing runtime or an unplugged GPU is a hard `up` failure —
    which upgrade.py must see before it stops anything."""
    path = path or override_path()
    try:
        current = read_override(path)
    except ValueError as e:
        return [f"{e}. Re-run: {STEP_HINT}"]
    if current is None:
        return []
    runtime = docker_has_nvidia_runtime(run)
    if runtime is False:
        return [f"{path} gives the renderer an NVIDIA GPU, but Docker has no `nvidia` "
                f"runtime (the NVIDIA Container Toolkit is missing or not configured). "
                f"Fix the toolkit ({DOCS_HINT}) or turn GPU rendering off: {STEP_HINT}"]
    gpus = list_gpus(run)
    if gpus is None:
        return [f"{path} gives the renderer an NVIDIA GPU, but nvidia-smi does not run on "
                f"this machine (driver missing or not loaded). Fix the driver ({DOCS_HINT}) "
                f"or turn GPU rendering off: {STEP_HINT}"]
    if current["uuid"] not in {g.uuid for g in gpus}:
        return [f"{path} names GPU {current['uuid']} ({current['name']}), which is no "
                f"longer on this machine. Pick another or turn GPU rendering off: {STEP_HINT}"]
    return []


PROBE_RESULT_KEY = "gpu_probe_result"  # keep in sync with renderer/api/pipeline.py


def report_lines(db_path: Path) -> list[tuple[str, str]]:
    """(level, text) for `upgrade.py --check` / `service.py status`, where level
    is "ok", "warn" or "info". Read-only: the override, then the worker's last
    probe from the settings table."""
    import sqlite3
    lines = []
    try:
        current = read_override()
    except ValueError as e:
        return [("warn", str(e))]
    problems = override_problems()
    for problem in problems:
        lines.append(("warn", problem))
    if problems:
        # The override cannot be applied, so advice about recreating the
        # renderer with it would only fail the same way.
        return lines
    probe = None
    if Path(db_path).exists():
        try:
            con = sqlite3.connect(f"file:{db_path}?mode=ro", uri=True)
            try:
                row = con.execute("SELECT value FROM settings WHERE key = ?",
                                  (PROBE_RESULT_KEY,)).fetchone()
            finally:
                con.close()
            probe = json.loads(row[0]) if row and row[0] else None
        except (sqlite3.Error, ValueError):
            probe = None
    if current is None:
        lines.append(("info", "Rendering on the CPU (no GPU chosen — to add one: "
                              f"{STEP_HINT})"))
    elif not isinstance(probe, dict) or not probe.get("configured"):
        lines.append(("warn", f"GPU {current['name']} is chosen, but the running renderer has "
                              "not reported it — recreate it with: "
                              "python3 scripts/service.py start tubematic-renderer"))
    elif probe.get("ok"):
        lines.append(("ok", f"Rendering on {current['name']} ({probe.get('renderer', '')})"))
    else:
        lines.append(("warn", f"GPU {current['name']} is chosen but not usable — rendering on "
                              f"the CPU: {probe.get('error') or 'see the worker log'}"))
    return lines
